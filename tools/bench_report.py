"""docs/BENCHMARK.md: precision, recall and F1 per category and per framework, the false negatives, and the
comparison with Semgrep and Bandit. Run through `python tools/benchmark.py report`."""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Callable, Dict, List, Tuple

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "benchmark"
SLACK = 3  # lines around the known location that still count as detecting it


def framework_of(path: Path) -> str:
    """The main framework of a checked-out repository, from its manifests (a label for grouping, not a claim)."""
    deps = ""
    for f in list(path.glob("package.json")) + list(path.glob("*/package.json")):
        deps += f.read_text(encoding="utf-8", errors="replace")
    for f in list(path.glob("requirements*.txt")) + list(path.glob("pyproject.toml")) + list(path.glob("*/requirements*.txt")) \
            + list(path.glob("*/pyproject.toml")):
        deps += f.read_text(encoding="utf-8", errors="replace").lower()
    if (path / "go.mod").is_file():
        return "go"
    for name, key in (("next.js", '"next"'), ("nestjs", "@nestjs/core"), ("express", '"express"'), ("supabase+react", "@supabase/supabase-js"),
                      ("django", "django"), ("fastapi", "fastapi"), ("flask", "flask")):
        if key in deps:
            return name
    if list(path.glob("**/*.tf"))[:1]:
        return "terraform"
    return "other"


def _f1(p: float, r: float) -> float:
    return 2 * p * r / (p + r) if p + r else 0.0


def _pct(x: float) -> str:
    return f"{x:.0%}"


def build(results: dict, corpus: List[dict], checkout: Callable[[dict], Path], scan_repo: Callable[[dict], List[dict]],
          rules_meta: Dict[str, object]) -> str:
    gt = json.loads((BENCH / "recall.json").read_text(encoding="utf-8"))["locations"]
    repos = {r["name"]: r for r in corpus}
    found_by_repo: Dict[str, List[dict]] = {}
    for name in sorted({g["repo"] for g in gt}):
        found_by_repo[name] = scan_repo(repos[name])
    detected: List[Tuple[dict, bool]] = []
    for g in gt:
        a, b = g["lines"]
        hit = any(f["file"] == g["file"] and f["rule"] in g["rules"] and a - SLACK <= f["line"] <= b + SLACK
                  for f in found_by_repo[g["repo"]])
        detected.append((g, hit))

    # precision per rule category and per framework, from the labelled findings
    cat_pr: Dict[str, List[int]] = defaultdict(lambda: [0, 0])
    fw_pr: Dict[str, List[int]] = defaultdict(lambda: [0, 0])
    fw_of = {r["name"]: framework_of(checkout(r)) if checkout(r).is_dir() else "other" for r in corpus}
    for rid, r in results["rules"].items():
        cat = getattr(rules_meta.get(rid), "category", "other")
        for repo, (tp, fp, *_rest) in r.get("by_repo", {}).items():
            cat_pr[cat][0] += tp
            cat_pr[cat][1] += fp
            fw_pr[fw_of.get(repo, "other")][0] += tp
            fw_pr[fw_of.get(repo, "other")][1] += fp

    # recall per category: advisory locations plus seeded cases (expect: markers)
    cat_rc: Dict[str, List[int]] = defaultdict(lambda: [0, 0])
    for g, hit in detected:
        cat_rc[g["category"]][0] += hit
        cat_rc[g["category"]][1] += 1
    seeded_cat: Dict[str, List[int]] = defaultdict(lambda: [0, 0])
    for rid, r in results["rules"].items():
        if r.get("seeded_expected"):
            cat = getattr(rules_meta.get(rid), "category", "other")
            seeded_cat[cat][0] += r["seeded_found"]
            seeded_cat[cat][1] += r["seeded_expected"]
    fw_rc: Dict[str, List[int]] = defaultdict(lambda: [0, 0])
    for g, hit in detected:
        fw_rc[g["framework"]][0] += hit
        fw_rc[g["framework"]][1] += 1

    adv_hit = sum(h for _, h in detected)
    seeded_total = [sum(v[0] for v in seeded_cat.values()), sum(v[1] for v in seeded_cat.values())]
    tp = sum(v[0] for v in cat_pr.values())
    fp = sum(v[1] for v in cat_pr.values())
    lines = [
        "# Benchmark: precision, recall and F1", "",
        "Generated by `python tools/benchmark.py report`; do not edit by hand. Per-rule precision: "
        "[benchmark/RESULTS.md](../benchmark/RESULTS.md).", "",
        "## What is measured", "",
        f"- **Precision** comes from {tp + fp:,} findings on {results['scanned']} pinned repositories, each read in the code and "
        "labelled true or false (both splits, preview rules included).",
        f"- **Recall** comes from two ground-truth sets: {len(gt)} known vulnerable locations in the repositories pinned at "
        "the commit before a published security advisory ([benchmark/recall.json](../benchmark/recall.json)), and "
        f"{seeded_total[1]} seeded cases (`expect:` markers in tests/fixtures and benchmark/seeded).",
        "- Seeded cases are written by us, so seeded recall is optimistic: it shows that a rule works on the case it was "
        "written for. The advisory set is small but independent: nobody wrote those bugs for this tool.", "",
        "## Overall", "",
        "| Measure | Value |", "| --- | --- |",
        f"| Precision, all labelled findings | {_pct(tp / max(1, tp + fp))} ({tp}/{tp + fp}) |",
        f"| Recall on the advisory locations | {_pct(adv_hit / max(1, len(gt)))} ({adv_hit}/{len(gt)}) |",
        f"| Recall on the seeded cases | {_pct(seeded_total[0] / max(1, seeded_total[1]))} ({seeded_total[0]}/{seeded_total[1]}) |",
        f"| F1, precision with advisory recall | {_pct(_f1(tp / max(1, tp + fp), adv_hit / max(1, len(gt))))} |", "",
        "## Per category", "",
        "| Category | Precision | Advisory recall | Seeded recall | F1 (advisory) |", "| --- | --- | --- | --- | --- |",
    ]
    for cat in sorted(set(cat_pr) | set(cat_rc) | set(seeded_cat)):
        p = cat_pr[cat][0] / max(1, sum(cat_pr[cat]))
        r = cat_rc[cat][0] / cat_rc[cat][1] if cat_rc[cat][1] else None
        s = seeded_cat[cat]
        lines.append(f"| {cat} | {_pct(p)} ({cat_pr[cat][0]}/{sum(cat_pr[cat])}) | "
                     f"{'n/a' if r is None else f'{_pct(r)} ({cat_rc[cat][0]}/{cat_rc[cat][1]})'} | "
                     f"{f'{s[0]}/{s[1]}' if s[1] else 'n/a'} | {'n/a' if r is None else _pct(_f1(p, r))} |")
    lines += ["", "## Per framework", "",
              "Frameworks are read from each repository's manifests; advisory recall uses the framework of the vulnerable code.", "",
              "| Framework | Precision | Advisory recall |", "| --- | --- | --- |"]
    for fw in sorted(set(fw_pr) | set(fw_rc)):
        p = fw_pr[fw]
        r = fw_rc[fw]
        lines.append(f"| {fw} | {f'{_pct(p[0] / max(1, sum(p)))} ({p[0]}/{sum(p)})' if sum(p) else 'n/a'} | "
                     f"{f'{_pct(r[0] / r[1])} ({r[0]}/{r[1]})' if r[1] else 'n/a'} |")
    lines += ["", "## False negatives (the misses)", "",
              "Every advisory location vibeaudit does not report, and why:", "",
              "| Advisory | Location | Class | Why it is missed |", "| --- | --- | --- | --- |"]
    for g, hit in detected:
        if not hit:
            lines.append(f"| {g['advisory']} ({g['repo']}) | `{g['file']}:{g['lines'][0]}` | {g['class']} | {g['note']} |")
    lines += ["", "Seeded misses (expected but not found): "
              + (", ".join(f"{rid} {r['seeded_found']}/{r['seeded_expected']}" for rid, r in sorted(results["rules"].items())
                           if r.get("seeded_expected") and r["seeded_found"] < r["seeded_expected"]) or "none") + ".", ""]
    lines += _comparison((tp, tp + fp))
    lines += ["## Limits", "",
              "- The advisory set has 17 locations in 7 repositories: enough to show the kinds of bug that are missed, not a "
              "precise recall figure. More pre-fix repositories are added as advisories are published.",
              "- Precision labels were made by the maintainers; a blind second labelling is in [docs/LABELLING.md](LABELLING.md).",
              "- The tuned split flatters precision (rules were fixed while looking at it); the held-out split does not "
              "(see benchmark/RESULTS.md).",
              "- \"Detected\" means a finding of a matching rule within 3 lines of the known location; a finding elsewhere "
              "in the same flow does not count.", ""]
    return "\n".join(lines)


def _comparison(own: Tuple[int, int] = (0, 0)) -> List[str]:
    path = BENCH / "compare.json"
    head = ["## Compared with Semgrep and Bandit", ""]
    if not path.is_file():
        return head + ["Not yet run: the comparison runs in CI (`.github/workflows/compare.yml`, Linux, manual and weekly) "
                       "and its results are committed to benchmark/compare.json.", ""]
    c = json.loads(path.read_text(encoding="utf-8"))
    out = head + [c.get("method", ""), "",
                  "| Tool | Advisory recall | Findings on the corpus | Precision |", "| --- | --- | --- | --- |"]
    for tool, t in c["tools"].items():
        prec = t.get("precision_sample")
        if tool == "vibeaudit":
            cell = f"{_pct(own[0] / max(1, own[1]))} ({own[0]}/{own[1]}, every finding labelled)"
        else:
            cell = f"about {_pct(prec[0] / max(1, prec[1]))} ({prec[0]}/{prec[1]} in a random sample)" if prec else "not yet labelled"
        out.append(f"| {tool} | {t['recall'][0]}/{t['recall'][1]} | {t['findings']:,} | {cell} |")
    recalls = {tool: tuple(t["recall"]) for tool, t in c["tools"].items()}
    hits = c.get("advisory_hits", {})
    if len(set(recalls.values())) == 1:
        r = next(iter(recalls.values()))
        found = sorted({k.split(":", 1)[0] for k, v in hits.items() if v})
        out += ["", f"All three tools find the same {r[0]} of the {r[1]} advisory locations ({', '.join(found)}) and miss the "
                    f"same {r[1] - r[0]}. Recall on these advisories is low for every tool, for the same reasons: the misses are "
                    "injections into query languages none of them models as a sink (KQL, Cypher, MongoDB filters reached "
                    "through an ORM or a JSON-parsed parameter), and flows that start at a library or agent-tool parameter "
                    "and cross modules before reaching the sink. What separates the tools on this corpus is precision and "
                    "the kinds of issue reported (Bandit reports Python hygiene such as asserts and bare excepts; Semgrep's "
                    "community rules report mutable action tags, template escaping and hardening settings), not recall on "
                    "these bugs."]
    elif c.get("overlap"):
        out += ["", f"Advisory locations found by more than one tool: {c['overlap']}."]
    return out + ["", c.get("limits", ""), ""]
